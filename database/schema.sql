-- Table 1: APP_USERS
-- Manages system login accounts with role-based access (ADMIN, RECEPTIONIST, DOCTOR)
CREATE TABLE APP_USERS (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR2(50) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    full_name     VARCHAR2(100) NOT NULL,
    user_role     VARCHAR2(20) DEFAULT 'RECEPTIONIST' NOT NULL,
    is_active     CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_app_users PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT chk_app_users_role CHECK (user_role IN ('ADMIN', 'RECEPTIONIST', 'DOCTOR')),
    CONSTRAINT chk_app_users_active CHECK (is_active IN ('Y', 'N'))
);

-- Table 2: PATIENTS
-- Stores registered patient demographics and contact details
CREATE TABLE PATIENTS (
    patient_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR2(100) NOT NULL,
    date_of_birth DATE,
    gender        VARCHAR2(20),
    phone         VARCHAR2(20) NOT NULL,
    email         VARCHAR2(120),
    address       VARCHAR2(300),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patients PRIMARY KEY (patient_id)
);

-- Table 3: DOCTORS
-- Stores registered doctors, specializations, fees, and active availability
CREATE TABLE DOCTORS (
    doctor_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name        VARCHAR2(100) NOT NULL,
    specialization   VARCHAR2(100) NOT NULL,
    phone            VARCHAR2(20),
    email            VARCHAR2(120),
    consultation_fee NUMBER(10,2) DEFAULT 0,
    is_active        CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_doctors PRIMARY KEY (doctor_id),
    CONSTRAINT chk_doctors_fee CHECK (consultation_fee >= 0),
    CONSTRAINT chk_doctors_active CHECK (is_active IN ('Y', 'N'))
);

-- Table 4: APPOINTMENTS
-- Schedules and records patient visits with doctors
CREATE TABLE APPOINTMENTS (
    appointment_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    patient_id           NUMBER NOT NULL,
    doctor_id            NUMBER NOT NULL,
    appointment_datetime TIMESTAMP NOT NULL,
    reason               VARCHAR2(500),
    status               VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_appointments PRIMARY KEY (appointment_id),
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) 
        REFERENCES PATIENTS (patient_id),
    CONSTRAINT fk_appointments_doctor FOREIGN KEY (doctor_id) 
        REFERENCES DOCTORS (doctor_id),
    CONSTRAINT chk_appointments_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED', 'NO_SHOW'))
);

-- Recommended Index for fast appointment schedule lookups and overlap checks:
CREATE INDEX idx_appointments_doc_time ON APPOINTMENTS(doctor_id, appointment_datetime, status);
CREATE INDEX idx_appointments_pat_time ON APPOINTMENTS(patient_id, appointment_datetime);
